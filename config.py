def _load_env() -> None:
    # 값을 바꾼 뒤 앱을 다시 켜지 않아도 되도록 읽을 때마다 .env 를 다시 로드합니다.
    # override=True: 컴퓨터에 남은 같은 이름의 환경변수보다 .env 값을 우선합니다.
    load_dotenv(ENV_PATH, override=True)


def get_api_key() -> str:
    _load_env()
    return os.getenv("OPENAI_API_KEY", "").strip()


def get_kakao_key() -> str:
    _load_env()
    return os.getenv("KAKAO_REST_API_KEY", "").strip()


def get_model_name() -> str:
    _load_env()
    return os.getenv("OPENAI_MODEL", "").strip() or DEFAULT_MODEL


def get_agent_mode() -> str:
    """질문 처리 방식. modular(에이전트·도구 모듈형, 기본) 또는 legacy(기존 방식).
    문제가 생기면 .env 에 AGENT_MODE=legacy 를 적고 서버를 다시 켜면 예전 방식으로 돌아갑니다."""
    mode = (os.environ.get("AGENT_MODE") or "modular").strip().lower()
    return mode if mode in ("modular", "legacy") else "modular"
